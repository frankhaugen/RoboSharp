static string MermaidId(string name)
{
    var sb = new StringBuilder(name.Length + 8);
    foreach (var c in name)
    {
        if (char.IsLetterOrDigit(c))
            sb.Append(c);
        else
            sb.Append('_');
    }

    if (sb.Length > 0 && char.IsDigit(sb[0]))
        sb.Insert(0, 'P');
    return sb.Length == 0 ? "node" : sb.ToString();
}

static string EscapeMermaidLabel(string text) =>
    text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);

static string FindRepoRoot()
{
    var dir = new DirectoryInfo(Directory.GetCurrentDirectory());
    while (dir is not null)
    {
        if (File.Exists(Path.Combine(dir.FullName, "RoboSharp.slnx")))
            return dir.FullName;
        dir = dir.Parent;
    }

    throw new InvalidOperationException(
        "Could not locate RoboSharp.slnx; pass the repository root as the first argument.");
}

file sealed class EdgeComparer : IEqualityComparer<(string From, string To)>
{
    public bool Equals((string From, string To) x, (string From, string To) y) =>
        string.Equals(x.From, y.From, StringComparison.OrdinalIgnoreCase)
        && string.Equals(x.To, y.To, StringComparison.OrdinalIgnoreCase);

    public int GetHashCode((string From, string To) obj) =>
        HashCode.Combine(
            StringComparer.OrdinalIgnoreCase.GetHashCode(obj.From),
            StringComparer.OrdinalIgnoreCase.GetHashCode(obj.To));
}

file sealed class PkgEdgeComparer : IEqualityComparer<(string Project, string Package, string? Version)>
{
    public bool Equals((string Project, string Package, string? Version) x, (string Project, string Package, string? Version) y) =>
        string.Equals(x.Project, y.Project, StringComparison.OrdinalIgnoreCase)
        && string.Equals(x.Package, y.Package, StringComparison.OrdinalIgnoreCase)
        && x.Version == y.Version;

    public int GetHashCode((string Project, string Package, string? Version) obj) =>
        HashCode.Combine(
            StringComparer.OrdinalIgnoreCase.GetHashCode(obj.Project),
            StringComparer.OrdinalIgnoreCase.GetHashCode(obj.Package),
            obj.Version?.GetHashCode(StringComparison.Ordinal) ?? 0);
}
